export function isHandleSafe(value) {
  const h = String(value || '')
    .trim()
    .toLowerCase()
  if (!h || h.length < 3 || h.length > 20) return false
  if (!/^[a-z0-9_]+$/.test(h)) return false
  return !HANDLE_BANNED.some((bad) => h.includes(bad))
}
